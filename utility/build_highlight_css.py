"""Write ``pyverse/static/css/code-highlight.css`` from ``PyVerseStyle``.

Run after editing ``pyverse/common/highlight_style.py``::

    uv run python utility/build_highlight_css.py

Only foreground colour and font style are emitted: the code surface itself
(background, padding, scrolling) belongs to the block and blog styles.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pygments.token import STANDARD_TYPES  # noqa: E402

from pyverse.common.highlight import CLASS_PREFIX  # noqa: E402
from pyverse.common.highlight_style import PyVerseStyle  # noqa: E402

SELECTORS = (".code-block", ".codehilite")
OUT = ROOT / "pyverse" / "static" / "css" / "code-highlight.css"


def build() -> str:
    rules = []
    for ttype, short in sorted(STANDARD_TYPES.items(), key=lambda item: item[1]):
        if not short:
            continue
        style = PyVerseStyle.style_for_token(ttype)
        declarations = []
        if style["color"]:
            declarations.append(f"color: #{style['color']}")
        if style["bold"]:
            declarations.append("font-weight: bold")
        if style["italic"]:
            declarations.append("font-style: italic")
        if style["underline"]:
            declarations.append("text-decoration: underline")
        if declarations:
            selector = ", ".join(f"{s} .{CLASS_PREFIX}{short}" for s in SELECTORS)
            rules.append(f"{selector} {{ {'; '.join(declarations)}; }}")
    header = (
        "/* GENERATED by utility/build_highlight_css.py from "
        "pyverse/common/highlight_style.py. Do not edit by hand. */\n"
    )
    return header + "\n".join(rules) + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")  # noqa: T201
